import { describe, expect, it } from "vitest";

import { buildFixture, readClientOutput, useFixture } from "../harness/fixture.js";
import { useBrowser } from "../harness/browser.js";

const FIXTURE = "stale-times";

// nlite.config.ts: staleTimes { static: 42, dynamic: 7 } (defaults are 300 and 0).
describe("staleTimes", () => {
  const app = useFixture(FIXTURE);
  const browser = useBrowser();

  describe("build output", () => {
    it("writes the configured static stale time for .rsc files to _headers", () => {
      expect(readClientOutput(FIXTURE, "_headers")).toContain("/*.rsc\n  x-nlite-staletime: 42");
    });

    it("writes the dynamic stale time for the not-found payload", () => {
      expect(readClientOutput(FIXTURE, "_headers")).toContain(
        "/_not-found.rsc\n  x-nlite-staletime: 7",
      );
    });

    it("keeps the user's public/_headers rules", () => {
      expect(readClientOutput(FIXTURE, "_headers")).toContain("/hello.txt\n  x-user-header: kept");
    });
  });

  describe("response headers", () => {
    it("sends the static stale time with prerendered payloads", async () => {
      for (const path of ["/static.rsc", "/.rsc"]) {
        expect((await app.fetch(path)).headers.get("x-nlite-staletime"), path).toBe("42");
      }
    });

    it("sends the dynamic stale time with on-demand HTML and payloads", async () => {
      for (const path of ["/dynamic", "/dynamic.rsc"]) {
        expect((await app.fetch(path)).headers.get("x-nlite-staletime"), path).toBe("7");
      }
    });

    it("sends the dynamic stale time with not-found payloads", async () => {
      expect((await app.fetch("/_not-found.rsc")).headers.get("x-nlite-staletime")).toBe("7");
      expect((await app.fetch("/missing.rsc")).headers.get("x-nlite-staletime")).toBe("7");
    });

    it("applies user _headers rules to public files", async () => {
      expect((await app.fetch("/hello.txt")).headers.get("x-user-header")).toBe("kept");
    });
  });

  describe("client route cache", () => {
    it("reuses a dynamic payload within the dynamic stale time", async () => {
      const { page, rscRequests } = await browser.open(app.url("/"));
      await page.locator("#to-dynamic").click();
      await page.locator("#dynamic").waitFor();
      const firstId = await page.locator("#render-id").textContent();
      await page.locator("#to-home").click();
      await page.locator("#home").waitFor();
      await page.locator("#to-dynamic").click();
      await page.locator("#dynamic").waitFor();

      expect(rscRequests().filter((request) => request === "/dynamic.rsc")).toHaveLength(1);
      expect(await page.locator("#render-id").textContent()).toBe(firstId);
    });

    it("reuses a static payload within the static stale time", async () => {
      const { page, rscRequests } = await browser.open(app.url("/"));
      await page.locator("#to-static").click();
      await page.locator("#static").waitFor();
      await page.locator("#to-home").click();
      await page.locator("#home").waitFor();
      await page.locator("#to-static").click();
      await page.locator("#static").waitFor();
      expect(rscRequests().filter((request) => request === "/static.rsc")).toHaveLength(1);
    });
  });

  // Runs last: rebuilding replaces the output the preview server is serving.
  describe("rebuilding", () => {
    it("does not duplicate the generated _headers section", async () => {
      const result = await buildFixture(FIXTURE);
      expect(result.code).toBe(0);
      const headers = readClientOutput(FIXTURE, "_headers");
      expect(headers.match(/Generated by nlite/g)).toHaveLength(1);
      expect(headers.match(/x-user-header: kept/g)).toHaveLength(1);
    });
  });
});
